"""Spec 172 §14 — Separate lifetime entitlement from bounded device credentials
(atom focusa-vbcqu.20.15.22, 172.03.05, lane spec152f / WPUIAI).

The WPUIAI issuer keeps the perpetual License Type entitlement (term
`lifetime`) in a ledger SEPARATE from the bounded signed device leases used
for execution. This gate proves, across PHP (issuer), Python (independent
Ed25519 + policy mirror), and Rust (state machine + signature verification):

- lifetime survives credential rotation and outage recovery: credential
  expiry resolves to recovery_only (never erasing the lifetime right) and
  verified recovery issues a replacement bounded lease;
- refund/revoke/higher sequence defeats stale and offline credentials: a
  revoked lifetime entitlement denies every credential regardless of window;
- Offline Grace stays bounded; stale sequences are never trusted; no
  caller-controlled product, price, License Type, family, feature, limit,
  node, or commercial right is accepted.

Exact verification:
    python3 tests/spec172_lifetime_credential_test.py \
        && cargo test -p focusa-license spec172_lifetime_credential

Exact surfaces:
- focusa-license authority verifier/store/refresh:
  crates/focusa-license/src/lifetime_entitlement.rs (lifecycle state machine +
  persisted store record + authority verifier adapter)
- WPUIAI lease/assertion issuer:
  docs/contracts/spec172-lifetime-entitlement-ledger.v1.php
- offline fixtures: docs/contracts/spec172-lifetime-credential-vectors.v1.json
  (regenerated byte-identically by the PHP issuer here)
- tests/spec172_lifetime_credential_test.py (this gate)
"""

