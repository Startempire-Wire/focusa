def expect(condition: bool, message: str, negative: bool = False) -> None:
    global POSITIVE, NEGATIVE
    if negative:
        NEGATIVE += 1
    else:
        POSITIVE += 1
    if not condition:
        raise AssertionError(f"FAIL: {message}")


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def canonical_payload(payload: dict) -> bytes:
    return json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()


def machine(entitlement: dict | None, credential: dict | None, now: str) -> str:
    """Python mirror of the joint lifecycle state machine (PHP + Rust)."""
    if entitlement is None:
        return "denied_unknown"
    if entitlement["status"] != "entitled":
        return "denied_revoked"
    if credential is None:
        return "recovery_only"
    if int(credential["sequence"]) < int(entitlement["sequence"]):
        return "denied_stale"
    if credential["status"] == "revoked":
        return "denied_revoked"
    if now <= credential["expires_at"]:
        return "active"
    if now <= credential["offline_grace_until"]:
        return "offline_grace"
    return "recovery_only"


